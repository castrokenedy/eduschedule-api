CREATE TABLE professores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    especialidade VARCHAR(120)
);
CREATE TABLE disciplinas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    carga_horaria INTEGER NOT NULL CHECK (carga_horaria > 0)
);
CREATE TABLE turmas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    periodo INTEGER NOT NULL CHECK (periodo > 0),
    semestre VARCHAR(10) NOT NULL
);
CREATE TABLE horarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professor_id BIGINT NOT NULL REFERENCES professores(id),
    disciplina_id BIGINT NOT NULL REFERENCES disciplinas(id),
    turma_id BIGINT NOT NULL REFERENCES turmas(id),
    dia_semana VARCHAR(10) NOT NULL CHECK (dia_semana IN ('SEGUNDA','TERCA','QUARTA','QUINTA','SEXTA','SABADO','DOMINGO')),
    hora_inicio TIME NOT NULL,
    hora_fim TIME NOT NULL,
    CONSTRAINT ck_horario_intervalo CHECK (hora_inicio < hora_fim)
);
CREATE INDEX idx_horario_professor ON horarios(professor_id, dia_semana, hora_inicio);
CREATE INDEX idx_horario_turma ON horarios(turma_id, dia_semana, hora_inicio);
CREATE INDEX idx_horario_disciplina ON horarios(disciplina_id);
